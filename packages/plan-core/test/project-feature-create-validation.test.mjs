test("feature create: explicit id/shortId/priority stored verbatim and stable", async () => {
  const { planRoot, store } = await createPlannerFixture({ name: "feat-explicit", seed: "empty" });
  const shortId = createShortId(new Set(), "feature-explicit");
  const id = createFeatureId();
  await store.saveFeature(makeFeature({ id, shortId, priority: 42, number: 3, name: "Explicit feature" }));
  const reopened = reopen(planRoot);
  const loaded = (await reopened.loadFeatures()).features.find((f) => f.id === id);
  assert.equal(loaded.id, id, "explicit id preserved");
  assert.equal(loaded.shortId, shortId, "explicit shortId preserved");
  assert.equal(loaded.priority, 42, "explicit priority preserved");
  assert.equal(loaded.number, 3);
  assert.equal(formatFeatureRef(loaded.number), "F003", "composite ref is stable");
  assert.match(loaded.shortId, /^[A-Z2-9]{5}$/);
  // per-feature file exists at features/<id>.json
  const raw = JSON.parse(await readFile(join(planRoot, "features", `${id}.json`), "utf-8"));
  assert.equal(raw.name, "Explicit feature");
  // generated markdown reflects creation ONLY after an explicit writeGenerated
  const beforeRegen = await planMd(planRoot);
  assert.ok(!beforeRegen.includes("Explicit feature"), "plain saveFeature does not auto-regenerate views");
  await store.writeGenerated();
  const md = await planMd(planRoot);
  assert.match(md, /F003 — Explicit feature/);
});

test("feature create: missing and empty names are rejected without writing a file", async () => {
  const { planRoot, store } = await createPlannerFixture({ name: "feat-name", seed: "empty" });
  await assert.rejects(() => store.saveFeature(makeFeature({ name: undefined })), /name/i);
  await assert.rejects(() => store.saveFeature(makeFeature({ name: "" })), /name/i);
  const files = await readdir(join(planRoot, "features"));
  assert.deepEqual(files, [], "no feature file written for rejected saves");
  const snapshot = await readPlanSnapshot(planRoot);
  assert.deepEqual(snapshot.features, []);
});

test("feature create: whitespace-only names and very long names are accepted (no trim/max at core)", async () => {
  const { planRoot, store } = await createPlannerFixture({ name: "feat-len", seed: "empty" });
  const longName = "F".repeat(2000);
  const id1 = createFeatureId();
  const id2 = createFeatureId();
  await store.saveFeature(makeFeature({ id: id1, name: "   " }));
  await store.saveFeature(makeFeature({ id: id2, number: 2, name: longName }));
  const reopened = reopen(planRoot);
  const loaded = await reopened.loadFeatures();
  assert.equal(loaded.features.find((f) => f.id === id1).name, "   ", "whitespace name stored verbatim");
  assert.equal(loaded.features.find((f) => f.id === id2).name.length, 2000, "no max length at core");
});

test("feature create: malformed fields are rejected by the schema", async () => {
  const { planRoot, store } = await createPlannerFixture({ name: "feat-malformed", seed: "empty" });
  await assert.rejects(() => store.saveFeature(makeFeature({ number: -1 })), /number/);
  await assert.rejects(() => store.saveFeature(makeFeature({ priority: -5 })), /priority/);
  for (const shortId of ["abcde", "AB1DE", "ABCDEF", "A B C", "ABCD*"]) {
    await assert.rejects(() => store.saveFeature(makeFeature({ shortId })), /shortId/);
  }
  await assert.rejects(() => store.saveFeature(makeFeature({ phaseIds: [""] })), /phaseIds/);
  // empty shortId is the documented default
  await store.saveFeature(makeFeature({ shortId: "" }));
  // non-UUID phaseIds are accepted on WRITE (min(1) string; UUID gates are
  // API-level) but pruned on LOAD by normalizeStructureSnapshot (self-healing
  // reads, same contract pinned in T230 for dangling feature→phase refs)
  const id = createFeatureId();
  await store.saveFeature(makeFeature({ id, phaseIds: ["not-a-uuid"] }));
  const raw = JSON.parse(await readFile(join(planRoot, "features", `${id}.json`), "utf-8"));
  assert.deepEqual(raw.phaseIds, ["not-a-uuid"], "stored verbatim on write");
  assert.deepEqual(
    (await store.loadFeatures()).features.find((f) => f.id === id).phaseIds,
    [],
    "unresolvable phaseIds pruned on load",
  );
});

test("feature create: missing/invalid timestamps are rejected", async () => {
  const { store } = await createPlannerFixture({ name: "feat-ts", seed: "empty" });
  const noCreated = makeFeature();
  delete noCreated.createdAt;
  await assert.rejects(() => store.saveFeature(noCreated), /createdAt/);
  const noUpdated = makeFeature();
  delete noUpdated.updatedAt;
  await assert.rejects(() => store.saveFeature(noUpdated), /updatedAt/);
  await assert.rejects(() => store.saveFeature(makeFeature({ createdAt: "2026-01-01" })), /createdAt/);
  await assert.rejects(() => store.saveFeature(makeFeature({ updatedAt: "not-a-date" })), /updatedAt/);
});

test("feature create: duplicate names allowed at core; non-UUID ids stored verbatim", async () => {
  const { planRoot, store } = await createPlannerFixture({ name: "feat-dup", seed: "empty" });
  const id1 = createFeatureId();
  const id2 = createFeatureId();
  await store.saveFeature(makeFeature({ id: id1, number: 1, name: "Same name" }));
  await store.saveFeature(makeFeature({ id: id2, number: 2, name: "Same name" }));
  const reopened = reopen(planRoot);
  const loaded = await reopened.loadFeatures();
  assert.equal(loaded.features.length, 2, "duplicate names both persist (no uniqueness at core)");
  assert.ok(loaded.features.every((f) => f.name === "Same name"));
  assert.notEqual(loaded.features[0].id, loaded.features[1].id);

  // non-UUID id: the core schema is a plain string — enforcement lives at API
  const customId = "custom-feature-1";
  await store.saveFeature(makeFeature({ id: customId, number: 3, name: "Custom id" }));
  const loadedCustom = (await reopen(planRoot).loadFeatures()).features.find((f) => f.id === customId);
  assert.equal(loadedCustom?.name, "Custom id", "non-UUID id stored verbatim at core");
});

