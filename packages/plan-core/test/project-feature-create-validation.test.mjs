const NOW = BASE_TIME;
const TS = { createdAt: NOW, updatedAt: NOW };

/** Raw (unparsed) feature — saveFeature/FeatureSchema does the validation. */
function makeFeature(overrides = {}) {
  return {
    id: createFeatureId(),
    number: 1,
    shortId: createShortId(new Set(), "feature"),
    priority: 10,
    name: "Auth API",
    description: "Authentication API.",
    phaseIds: [],
    ...TS,
    ...overrides,
  };
}

async function planMd(planRoot) {
  return readFile(join(planRoot, ".local", "generated", "PLAN.md"), "utf-8");
}

function reopen(planRoot) {
  const store = new PlanStore(planRoot);
  store.enableAutoSync(true);
  return store;
}

