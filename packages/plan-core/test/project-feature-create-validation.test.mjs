test("project init: creates the full deterministic tree and seeds counters to 1", async () => {
  const { planRoot, store } = await createPlannerFixture({ name: "init-tree", seed: "empty" });
  const paths = fixturePaths(planRoot);
  const snapshot = await readPlanSnapshot(planRoot);
  assert.equal(snapshot.manifest.projectName, "init-tree");
  assert.equal(snapshot.manifest.schemaVersion, 1);
  assert.deepEqual(snapshot.requirements, { requirements: [] });
  assert.deepEqual(snapshot.features, []);
  assert.deepEqual(snapshot.phases, []);
  assert.equal(snapshot.project.name, "init-tree");
  assert.equal(snapshot.project.nextFeatureNumber, 1);
  assert.equal(snapshot.project.nextPhaseNumber, 1);
  assert.equal(snapshot.project.nextTaskNumber, 1);
  assert.deepEqual(snapshot.project.scope, []);
  assert.deepEqual(snapshot.project.technologies, []);
  // generated views + resume are written at init
  const md = await planMd(planRoot);
  assert.match(md, /Project Plan/);
  const resume = JSON.parse(await readFile(paths.resume, "utf-8"));
  assert.equal(resume.currentPhaseId, "");
  assert.ok(Array.isArray(resume.nextSteps));
  void store;
});

test("project init: rejects when .planner/ already exists", async () => {
  const { planRoot } = await createPlannerFixture({ name: "init-twice", seed: "empty" });
  // same store
  await assert.rejects(() => new PlanStore(planRoot).init("second"), /already exists/);
  // fresh store over the same root
  await assert.rejects(() => reopen(planRoot).init("second"), /already exists/);
});

test("project init: empty name rejects and leaves no project.json; whitespace name is accepted", async () => {
  const { createTempRoot } = await import("../../../test/helpers/fixtures.mjs");
  const { readFile: rf } = await import("node:fs/promises");
  // empty name: init fails inside saveProject, so project.json must NOT exist.
  // (The dir tree IS created before saveProject — a later init on the same
  // root is rejected as "already exists", pinned below.)
  const bare1 = await createTempRoot("init-blank-");
  const fresh1 = new PlanStore(join(bare1, ".planner"));
  await assert.rejects(() => fresh1.init(""), /name/i);
  await assert.rejects(rf(join(bare1, ".planner", "project.json")), { code: "ENOENT" });
  await assert.rejects(() => fresh1.init("second"), /already exists/, "failed init still created the dir tree");
  // min(1) counts characters: a whitespace-only name passes the core schema
  const bare2 = await createTempRoot("init-ws-");
  const fresh2 = new PlanStore(join(bare2, ".planner"));
  await fresh2.init("   ");
  assert.equal((await fresh2.loadProject()).name, "   ");
});

