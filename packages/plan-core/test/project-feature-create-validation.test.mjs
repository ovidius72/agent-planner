/**
 * T228 (P053/F015) — Project and feature creation validation.
 *
 * Core-level coverage (real PlanStore + real filesystem, no mocks):
 *  - project init: full deterministic tree, counters seeded to 1, double-init
 *    rejection, empty-name rejection with no partial project.json
 *  - project update/persist: updateProject + saveProject round-trips through a
 *    fresh PlanStore; invalid updates reject WITHOUT mutating project.json;
 *    global sequence counters persist and reject non-positive values
 *  - feature create: explicit id/shortId/priority stored verbatim; missing and
 *    empty names rejected; whitespace-only names accepted (min(1) counts chars,
 *    no trim at core — API-layer concern); long names accepted (no max at core);
 *    malformed fields rejected (negative number/priority, bad shortId, empty
 *    phaseId, missing/invalid timestamps); duplicate names allowed (no
 *    uniqueness at core); non-UUID ids/phaseIds stored verbatim (UUID gate
 *    lives at adapter/API)
 *  - invalid saves do NOT write files (parse happens before atomic write)
 *  - feature update/delete via updateFeatures: rename+workDone persists; delete
 *    removes the feature FILE; phase files remain on disk → orphan phases
 *    reported (delete at core has no cascade — pin)
 *  - generated markdown: views are NOT auto-regenerated by plain feature/
 *    project writes — writeGenerated() must be called explicitly (pinned);
 *    after regeneration PLAN.md reflects the canonical JSON
 *  - stable refs: formatFeatureRef padding, explicit shortId survival
 *
 * Enforcement notes (recorded for later phases):
 *  - whitespace-only names/descriptions and duplicate names pass the core
 *    schema; stricter uniqueness/trim gates (if desired) live at the API layer
 *    (serve.ts, P054).
 *  - feature number assignment at creation lives in the API layer (POST
 *    /features); the core counter (project.nextFeatureNumber) is preserved here
 *    as the monotonic-sequence contract.
 */

