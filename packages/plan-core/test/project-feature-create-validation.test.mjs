test("feature update: rename + workDone persist; views update after explicit writeGenerated", async () => {
  const { planRoot, store } = await createPlannerFixture({ name: "feat-update", seed: "minimal" });
  const feature = (await store.loadFeatures()).features[0];
  await store.updateFeatures((doc) => {
    const f = doc.features.find((x) => x.id === feature.id);
    f.name = "Auth API v2";
    f.description = "Renamed during update.";
    f.workDone = "Schema + CRUD";
    f.workRemaining = "Tests";
    return doc;
  });
  const reopened = reopen(planRoot);
  const loaded = (await reopened.loadFeatures()).features.find((f) => f.id === feature.id);
  assert.equal(loaded.name, "Auth API v2");
  assert.equal(loaded.workDone, "Schema + CRUD");
  assert.equal(loaded.workRemaining, "Tests");
  const beforeRegen = await planMd(planRoot);
  assert.ok(!beforeRegen.includes("Auth API v2"), "plain updateFeatures does not auto-regenerate views");
  await store.writeGenerated();
  const md = await planMd(planRoot);
  assert.match(md, /F001 — Auth API v2/);
});

test("feature delete: removes the file and regenerates views; phases become orphans (no cascade)", async () => {
  const { planRoot, store } = await createPlannerFixture({ name: "feat-delete", seed: "minimal" });
  const feature = (await store.loadFeatures()).features[0];
  const phase = (await store.loadAllPhases())[0];
  await store.writeGenerated();
  const beforeMd = await planMd(planRoot);
  assert.match(beforeMd, /F001 — Auth API/, "PLAN.md lists the feature before deletion");

  await store.updateFeatures((doc) => {
    doc.features = doc.features.filter((f) => f.id !== feature.id);
    return doc;
  });
  const files = await readdir(join(planRoot, "features"));
  assert.ok(!files.includes(`${feature.id}.json`), "feature file removed");
  // views still stale until explicitly regenerated
  const staleMd = await planMd(planRoot);
  assert.ok(staleMd.includes("F001 — Auth API"), "views are not auto-regenerated by delete either");
  await store.writeGenerated();
  const md = await planMd(planRoot);
  assert.ok(!md.includes("F001 — Auth API"), "PLAN.md no longer lists the deleted feature after regen");
  // core delete has NO cascade: the phase file stays on disk and is reported as orphan
  const phaseFiles = await readdir(join(planRoot, "phases"));
  assert.equal(phaseFiles.length, 1, "phase file preserved (no cascade at core)");
  const orphans = await store.listOrphanPhases();
  assert.equal(orphans.length, 1);
  assert.equal(orphans[0].phaseId, phase.id, "orphan points at the unlinked phase");
  assert.ok((await store.loadAllPhases()).some((p) => p.id === phase.id), "phase still loadable");
});

test("feature update: invalid document rejects and leaves files unchanged", async () => {
  const { planRoot, store } = await createPlannerFixture({ name: "feat-invalid-update", seed: "minimal" });
  const before = await readdir(join(planRoot, "features"));
  const beforeMd = await planMd(planRoot);
  await assert.rejects(
    () => store.updateFeatures((doc) => {
      doc.features[0].name = "";
      return doc;
    }),
    /name/,
  );
  const after = await readdir(join(planRoot, "features"));
  assert.deepEqual(after, before, "no feature files changed");
  assert.equal(await planMd(planRoot), beforeMd, "generated view unchanged");
});
